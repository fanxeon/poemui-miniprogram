'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.resolve(__dirname, '..');
var packageJson = require(path.join(ROOT, 'package.json'));
var updateAnnouncements = require(path.join(ROOT, 'miniprogram/common/services/update-announcements'));
var announcements = updateAnnouncements.list();

if (!announcements.length || announcements[0].version !== 'v' + packageJson.version) {
  throw new Error('release notes latest version must match package.json');
}

var payload = {
  version: packageJson.version,
  announcements: announcements
};
var output = [
  '/* Generated by scripts/generate-release-notes.js. Do not edit manually. */',
  'window.POEMUI_RELEASE_NOTES = ' + JSON.stringify(payload, null, 2) + ';',
  ''
].join('\n');

fs.writeFileSync(path.join(ROOT, 'preview/release-notes-data.js'), output);
console.log('generated preview/release-notes-data.js with ' + announcements.length + ' releases');
