const fs = require('fs');
const path = require('path');
const { packageComponents } = require('../metadata/components');

const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'miniprogram_dist');
const runtimeEntries = ['assets', 'common', 'theme', ...packageComponents];

function copy(source, destination) {
  const stat = fs.statSync(source);
  if (stat.isDirectory()) {
    fs.mkdirSync(destination, { recursive: true });
    for (const entry of fs.readdirSync(source)) {
      copy(path.join(source, entry), path.join(destination, entry));
    }
    return;
  }
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(source, destination);
}

function createDistEntrySource(sourceEntry) {
  const componentRequires = packageComponents
    .map((component) => `require('./${component}/${component}');`)
    .join('\n');

  return [
    '/* This file is generated by scripts/generate-miniprogram-dist.js. Do not edit manually. */',
    '/* Keep every native component in the WeChat npm compiler dependency graph. */',
    componentRequires,
    '',
    sourceEntry.trim(),
    '',
  ].join('\n');
}

function build() {
  fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist, { recursive: true });

  for (const entry of runtimeEntries) {
    copy(path.join(root, entry), path.join(dist, entry));
  }

  const sourceEntry = fs.readFileSync(path.join(root, 'index.js'), 'utf8');
  fs.writeFileSync(path.join(dist, 'index.js'), createDistEntrySource(sourceEntry));

  console.log(`Generated miniprogram_dist with ${packageComponents.length} component directories.`);
}

if (require.main === module) build();

module.exports = { build, createDistEntrySource };
