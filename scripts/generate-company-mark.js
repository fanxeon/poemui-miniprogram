const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const svg2ttf = require('svg2ttf');
const wawoff2 = require('wawoff2');

const root = path.resolve(__dirname, '..');
const outputRoot = path.join(root, 'assets', 'company-mark');
const fontFamily = 'PoemUI Company Mark';
const glyphName = 'company-mark';
const codepoint = 'E001';
const fontUnits = 1024;
const sourceUnits = 24;

// Five closed silhouettes optically simplified from the user-owned raster logo.
// The final subpath runs in the opposite direction and preserves the central eye.
