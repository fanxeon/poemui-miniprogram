const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'input-otp/input-otp.js'), 'utf8');
const wxml = fs.readFileSync(path.join(root, 'input-otp/input-otp.wxml'), 'utf8');
const wxss = fs.readFileSync(path.join(root, 'input-otp/input-otp.wxss'), 'utf8');
const preview = fs.readFileSync(path.join(root, 'preview/app.js'), 'utf8');
const contract = fs.readFileSync(path.join(root, 'docs/components/INPUT-OTP.md'), 'utf8');
let definition;
vm.runInNewContext(source, { Component(value) { definition = value; }, require() { return {}; } });
assert(definition && Object.keys(definition.properties).length === 8);
assert(wxml.includes('bindinput="onInput"') && wxml.includes('maxlength="{{index === activeIndex ? 8 : 1}}"'));
assert(wxss.includes('background:var(--pui-bg-muted)'), 'InputOTP 空单元格必须在全局边框关闭时仍有可见 Surface');
assert(wxss.includes('.pui-input-otp__cell:focus{background:var(--pui-bg-container);border-color:var(--pui-color-brand)}'), 'InputOTP 聚焦态必须同时提供 Surface 与品牌边界反馈');
assert(contract.includes("updateCurrentProp('value')"));
assert(preview.includes("updateCurrentProp('value', cells.join(''))"));
assert(preview.includes("action === 'otp-input' && previewIdFor(state.current) === 'input-otp'"));
assert(preview.includes("action !== 'otp-input' || previewIdFor(state.current) !== 'input-otp'"));
function create(overrides) { const defaults = Object.fromEntries(Object.entries(definition.properties).map(([key, value]) => [key, value.value])); const events=[]; const instance={data:{...definition.data,...defaults,...overrides},getColorSchemeClass(){return 'pui-theme-light';},setData(patch){Object.assign(this.data,patch);},triggerEvent(name,detail){events.push({name,detail});}}; Object.assign(instance,definition.methods); instance.syncState(); return {instance,events}; }
const otp = create({ value: '', length: 4 });
otp.instance.onInput({ currentTarget:{dataset:{index:'0'}}, detail:{value:'12'} });
assert.strictEqual(otp.events[0].detail.value, '12');
assert.deepStrictEqual(otp.events.map((event)=>event.name), ['input','change']);
otp.instance.onInput({ currentTarget:{dataset:{index:'2'}}, detail:{value:'34'} });
assert.strictEqual(otp.events.at(-1).name,'complete');
assert.strictEqual(otp.events.at(-1).detail.value,'1234');
const disabled=create({disabled:true}); disabled.instance.onInput({currentTarget:{dataset:{index:'0'}},detail:{value:'1'}}); assert.strictEqual(disabled.events.length,0);
console.log('InputOTP contract tests passed.');
